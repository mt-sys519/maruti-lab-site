import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// HALLO TERRA's palette, derived rather than picked.
//
// The source values are the ones headspace.com actually paints with, read off
// the running page on 2026-09-19: a warm near-white ground, a near-black, and
// a handful of unmixed colours used in small amounts. That arrangement is what
// we want. What we do not want is the finish - those colours are screen-bright
// and sit badly next to a drawn line - so every one of them goes through the
// same wax: a nudge toward the warm side of its own hue, some saturation taken
// out, and the lightness pulled toward the middle. One operation, applied to
// all of them, so they stay a family.
//
//   node scripts/hallo-terra-palette.mjs
const SOURCE = {
  paper: "#f9f4f2",
  ink: "#2d2c2b",
  blue: "#0061ef",
  sky: "#00a4ff",
  yellow: "#ffce00",
  green: "#02873e",
  purple: "#3b197f",
  pink: "#ffa1cc",
};

const hex = (n) => Math.round(Math.min(255, Math.max(0, n))).toString(16).padStart(2, "0");
const toHex = ([r, g, b]) => `#${hex(r)}${hex(g)}${hex(b)}`;
const fromHex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));

function toHsl([r, g, b]) {
  const [R, G, B] = [r / 255, g / 255, b / 255];
  const max = Math.max(R, G, B);
  const min = Math.min(R, G, B);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === R) h = ((G - B) / d + (G < B ? 6 : 0)) / 6;
  else if (max === G) h = ((B - R) / d + 2) / 6;
  else h = ((R - G) / d + 4) / 6;
  return [h * 360, s, l];
}

function toRgb([h, s, l]) {
  const H = ((h % 360) + 360) % 360 / 360;
  if (s === 0) return [l * 255, l * 255, l * 255];
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  const channel = (t) => {
    let T = t;
    if (T < 0) T += 1;
    if (T > 1) T -= 1;
    if (T < 1 / 6) return p + (q - p) * 6 * T;
    if (T < 1 / 2) return q;
    if (T < 2 / 3) return p + (q - p) * (2 / 3 - T) * 6;
    return p;
  };
  return [channel(H + 1 / 3) * 255, channel(H) * 255, channel(H - 1 / 3) * 255];
}

// The wax. Warm is 45 degrees, the hue of ochre, and every colour is drawn the
// same fraction of the way toward it. Then the saturation comes down, and the
// lightness is pulled toward the middle rather than up: a crayon is never as
// bright as a screen and never as pale either, and lifting the dark ones
// toward white turned the green into a highlighter. Greys are left alone -
// there is nothing to wax in a colour that has no colour in it.
const WARM = 45;
const MIDDLE = 0.55;
function wax(h) {
  let [hue, s, l] = toHsl(fromHex(h));
  if (s < 0.08) return h;
  const toward = ((((WARM - hue) % 360) + 540) % 360) - 180;
  hue += toward * 0.08;
  s *= 0.75;
  l += (MIDDLE - l) * 0.35;
  return toHex(toRgb([hue, s, l]));
}

// A ground is the waxed colour let down into the paper: same hue, none of the
// force. The fraction is how much of the colour is left in it.
function tint(h, amount, over = "#fffdf6") {
  const a = fromHex(h);
  const b = fromHex(over);
  return toHex(a.map((v, i) => b[i] + (v - b[i]) * amount));
}

// Which of them the grounds are made of.
const GROUND = "blue";

const waxed = Object.fromEntries(Object.entries(SOURCE).map(([k, v]) => [k, wax(v)]));

for (const [name, from] of Object.entries(SOURCE)) {
  process.stdout.write(`${name.padEnd(7)} ${from} -> ${waxed[name]}\n`);
}

const css = `/* Generated by scripts/hallo-terra-palette.mjs - do not edit by hand.
   Source: the colours headspace.com paints with, read off the page on
   2026-09-19, each put through the same wax. See the script for the sums. */

.terraSkin {
  --terra-greeting: ${waxed.blue};
  --terra-thanks: ${waxed.green};
  --terra-apology: ${waxed.purple};
  --terra-sky: ${waxed.sky};
  --terra-wax: ${waxed.yellow};
  --terra-rose: ${waxed.pink};

  /* The grounds: one colour at three distances, not three colours. The strip
     round the name carries it, the card behind the words barely does, and the
     writing below is nearly paper. */
  --terra-paper: ${tint(waxed[GROUND], 0.42)};
  --terra-card: ${tint(waxed[GROUND], 0.08)};
  --terra-notes: ${tint(waxed[GROUND], 0.03)};

  /* The map keeps the sand and the sea that were already right. */
  --terra-sea: #cfe2e8;
  --terra-land: #ecdfc6;
  --terra-line: #b09876;
  --terra-rule: ${tint(waxed[GROUND], 0.5, "#c9bda0")};
}
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "app", "hallo-terra", "palette.generated.css");
await writeFile(out, css);
process.stdout.write(`\npaper ${tint(waxed.yellow, 0.5)}  card ${tint(waxed.yellow, 0.2)}  notes ${tint(waxed.yellow, 0.05)}\n`);
